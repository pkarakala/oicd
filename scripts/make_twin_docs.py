"""Generate docs/twin/<product>.md and docs/lightmatter_public_spec_sheet.md from the catalog.

Every number comes from the engine's evaluation of the catalog (oicd.twin), with its class.
Run: uv run python scripts/make_twin_docs.py
"""

import sys
from pathlib import Path

from oicd.provenance import DEFAULT_BIB_PATH, parse_bib_entries
from oicd.twin.catalog import Catalog, load_catalog
from oicd.twin.formulas import format_number
from oicd.twin.inference import EvaluatedGraph, NodeResult, evaluate_graph
from oicd.twin.physics import physics_for

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "twin"
INDEPENDENCE = (
    "Independent reconstruction from public information. Not affiliated with or endorsed by "
    "Lightmatter. Product names belong to their owners."
)
CLASS = {
    "published_spec": "PUBLISHED_SPEC",
    "proposed_standard": "PROPOSED_STANDARD",
    "vendor_claim": "VENDOR_CLAIM",
    "peer_reviewed": "PEER_REVIEWED",
    "third_party": "THIRD_PARTY",
    "synthetic": "SYNTHETIC",
    "inference": "INFERENCE",
}
BIB = {e.key: e for e in parse_bib_entries(DEFAULT_BIB_PATH.read_text(encoding="utf-8"))}


def cell(text: str) -> str:
    return " ".join(str(text).replace("|", "\\|").split())


def cite(key: str | None) -> str:
    if not key:
        return ""
    entry = BIB.get(key)
    return f"[{key}]({entry.url})" if entry and entry.url else f"`{key}`"


def value(n: NodeResult) -> str:
    if n.nominal is None:
        return "text"
    unit = "" if n.unit in ("1", "count", "text") else f" {n.unit}"
    bound = {"min": "≥ ", "max": "≤ ", "approx": "≈ "}.get(n.bound or "", "")
    text = f"{bound}{format_number(n.nominal)}{unit}"
    ranged = n.lo is not None and n.hi is not None and (n.lo, n.hi) != (n.nominal, n.nominal)
    if n.kind != "fact" and ranged and n.lo is not None and n.hi is not None:
        text += f" ({format_number(n.lo)} to {format_number(n.hi)})"
    return text


def product_page(catalog: Catalog, stem: str) -> str:
    f = catalog.files[stem]
    graph: EvaluatedGraph = evaluate_graph(catalog, stem)
    own = [n for n in graph.nodes if n.file == stem]
    facts = [n for n in own if n.kind == "fact"]
    assumptions = [n for n in own if n.kind == "assumption"]
    derived = [n for n in own if n.kind == "derived"]
    lines = [
        f"# {f.product.name}",
        "",
        f"_{INDEPENDENCE}_",
        "",
        f"{f.product.summary}",
        "",
        f"Status: {f.product.status}. Catalog file `catalog/products/{stem}.toml`: "
        f"{len(facts)} facts ({sum(1 for x in facts if x.verified)} verified against their "
        f"source), {len(assumptions)} assumptions, {len(derived)} derived values, "
        f"{len(graph.checks)} checks. Generated by `scripts/make_twin_docs.py`; every number "
        "carries its class.",
        "",
    ]
    if facts:
        lines += ["## Spec table (facts)", "", "| quantity | value | class | source |"]
        lines += ["| --- | --- | --- | --- |"]
        for n in sorted(facts, key=lambda x: x.id):
            mark = "" if n.verified else " (not verified)"
            lines.append(
                f"| {cell(n.label)} | {cell(value(n))} | {CLASS[n.source_class.value]}{mark} | "
                f"{cite(n.cite)} |"
            )
        lines.append("")
    if derived:
        lines += ["## Inference highlights (INFERENCE)", ""]
        lines += [f"- {cell(n.label)}: `{n.derivation}`" for n in derived]
        lines.append("")
    if graph.checks:
        lines += ["## Checks", "", "| check | status | result |", "| --- | --- | --- |"]
        lines += [f"| `{c.id}` | {c.status} | {cell(c.explanation)} |" for c in graph.checks]
        lines.append("")
    open_items = [c for c in graph.checks if c.status != "CONSISTENT"]
    if open_items or graph.conflicts:
        lines += ["## Open tensions and conflicts", ""]
        for c in open_items:
            note = next((x.note for x in f.check if x.id == c.id), "")
            lines.append(f"- {c.status}: `{c.id}`: {cell(c.explanation)}. {cell(note)}")
        for p in graph.conflicts:
            lines.append(
                f"- CONFLICT: {cell(p.quantity_a)}: {cell(p.value_a)} (“{cell(p.quote_a)}”, "
                f"{cite(p.cite_a)}) against {cell(p.quantity_b)}: {cell(p.value_b)} "
                f"(“{cell(p.quote_b)}”, {cite(p.cite_b)}). Both are kept."
            )
        lines.append("")
    if len(graph.support) > 1:
        lines += ["## Hypotheses", ""]
        for row in graph.support[1:]:
            agrees = ", ".join(f"`{c}`" for c in row.agrees) or "none"
            disagrees = ", ".join(f"`{c}`" for c in row.disagrees) or "none"
            lines.append(
                f"- `{row.hypothesis}`: {cell(row.statement)} Agrees with {agrees}; "
                f"not with {disagrees}."
            )
        lines.append("")
    if assumptions:
        lines += [
            "## Not disclosed (assumptions, SYNTHETIC)",
            "",
            "| assumption | nominal (range) | why it is needed |",
            "| --- | --- | --- |",
        ]
        lines += [f"| `{n.id}` | {cell(value(n))} | {cell(n.label)} |" for n in assumptions]
        lines.append("")
    unverified = [n for n in facts if not n.verified]
    if unverified:
        lines += ["## Facts not verified", ""]
        lines += [f"- `{n.id}`: {cell(n.label)} ({cite(n.cite)})" for n in unverified]
        lines.append("")
    physics = physics_for(catalog, stem)
    if physics is not None:
        lines += ["## Physics (engine evaluations)", ""]
        for s in physics.sections:
            head = f"### {s.title}"
            if s.hypothesis:
                head += f" ({s.hypothesis})"
            lines += [head, ""]
            if s.verdict:
                lines += [f"Verdict: {s.verdict}.", ""]
            lines += ["| item | value | class |", "| --- | --- | --- |"]
            for item in s.items:
                v = format_number(item.value) if isinstance(item.value, float) else item.value
                lines.append(
                    f"| {cell(item.label)} | {cell(f'{v} {item.unit}'.strip())} | "
                    f"{CLASS[item.source_class.value]} |"
                )
            if s.note:
                lines += ["", s.note]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def spec_sheet(catalog: Catalog) -> str:
    lines = [
        "# Lightmatter public spec sheet (as reconstructed by OICD)",
        "",
        f"_{INDEPENDENCE}_",
        "",
        "One reading document generated from the catalog by `scripts/make_twin_docs.py`: every "
        "public number with its class (VENDOR_CLAIM, PEER_REVIEWED, THIRD_PARTY, ...) and source. "
        "Derived values, checks and hypotheses are in the per-product pages under docs/twin/.",
        "",
    ]
    for stem in sorted(catalog.files):
        f = catalog.files[stem]
        if f.product.kind != "product":
            continue
        graph = evaluate_graph(catalog, stem)
        facts = [n for n in graph.nodes if n.file == stem and n.kind == "fact"]
        if not facts:
            continue
        lines += [
            f"## {f.product.name}",
            "",
            f.product.summary,
            "",
            "| quantity | value | class | source |",
            "| --- | --- | --- | --- |",
        ]
        for n in sorted(facts, key=lambda x: x.id):
            mark = "" if n.verified else " (not verified)"
            lines.append(
                f"| {cell(n.label)} | {cell(value(n))} | {CLASS[n.source_class.value]}"
                f"{mark} | {cite(n.cite)} |"
            )
        lines += ["", f"Details: [docs/twin/{stem}.md](twin/{stem}.md).", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    catalog = load_catalog()
    OUT.mkdir(parents=True, exist_ok=True)
    for stem in sorted(catalog.files):
        path = OUT / f"{stem}.md"
        path.write_text(product_page(catalog, stem), encoding="utf-8")
        print(path.relative_to(ROOT))
    sheet = ROOT / "docs" / "lightmatter_public_spec_sheet.md"
    sheet.write_text(spec_sheet(catalog), encoding="utf-8")
    print(sheet.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
